# 1. CARGA DE DATOS DESDE EXCEL Y CONSOLIDACIÓN DE MUNICIPIOS
# ==============================================================================
import pandas as pd
import numpy as np

# Cargar el archivo original de Excel (.xlsx)
# Asegúrate de subirlo a Google Colab con este nombre exacto
df_original = pd.read_excel('AFECTACIÓN A LA FUERZA PÚBLICA.xlsx', header=0)

# Columnas identificadoras
index_cols = ['COD_MUNI', 'MUNICIPIO', 'DEPARTAMENTO']

# Pivotamos las variables categóricas para convertirlas en conteos numéricos por municipio
pivot_accion = df_original.pivot_table(index=index_cols, columns='ACCION', values='CANTIDAD', aggfunc='sum', fill_value=0)
pivot_fuerza = df_original.pivot_table(index=index_cols, columns='NOMBRE_FUERZA', values='CANTIDAD', aggfunc='sum', fill_value=0)
pivot_cat = df_original.pivot_table(index=index_cols, columns='CATEGORIA', values='CANTIDAD', aggfunc='sum', fill_value=0)
total_municipio = df_original.groupby(index_cols)['CANTIDAD'].sum().to_frame(name='TOTAL_AFECTADOS')

# Unimos todo para crear la base consolidada de 884 municipios y sus nuevas variables numéricas
datos = total_municipio.join([pivot_accion, pivot_fuerza, pivot_cat]).reset_index()

# Renombramos temporalmente el identificador principal a 'State' para acoplarnos al código de la profesora
datos = datos.rename(columns={'MUNICIPIO': 'State'})

print(f"¡Base de datos preparada desde Excel! Filas (Municipios): {datos.shape[0]} | Columnas: {datos.shape[1]}")
