# 7. EJECUCIÓN DEL ALGORITMO K-MEANS CON K=4
# ==============================================================================
import time

random_seed = 42
kmeans = KMeans(n_clusters=4, n_init=50, random_state=random_seed)

# Ajustar modelo
start = time.time()
km4_clusters = kmeans.fit(X_scaled)
print("KMEANS tomó: %.2f ms" % ((time.time() - start)*1000))

print("\nCentroides (coordenadas escaladas):\n", km4_clusters.cluster_centers_)
print("\nEtiquetas de los clústers asignados a los primeros 20 municipios:\n", km4_clusters.labels_[:20])
print("\nInercia Total (WSS final):", km4_clusters.inertia_)

# ==============================================================================
# 8. REDUCCIÓN DIMENSIONAL (PCA) Y VISUALIZACIÓN CON ELIPSES
# ==============================================================================
from sklearn.decomposition import PCA
from matplotlib.patches import Ellipse

pca = PCA(n_components=2)
datos_pca = pca.fit_transform(X_scaled)

# Construir DataFrame de visualización
datos_pca_df = pd.DataFrame(data=datos_pca, columns=['PCA1', 'PCA2'])
datos_pca_df['Cluster'] = km4_clusters.labels_

plt.figure(figsize=(14, 10))
colores = ['red', 'green', 'blue', 'yellow']

# Dibujar Municipios
sns.scatterplot(x='PCA1', y='PCA2', hue='Cluster', data=datos_pca_df, palette=colores, s=40, alpha=0.7)

# Dibujar Centroides
centroids_pca = pca.transform(kmeans.cluster_centers_)
plt.scatter(centroids_pca[:, 0], centroids_pca[:, 1], s=400, c=colores, marker='*', edgecolor='black', label='Centroides')

# Dibujar las elipses de covarianza por grupo
for i, color in enumerate(colores):
    cluster_points = datos_pca_df[datos_pca_df['Cluster'] == i][['PCA1', 'PCA2']]
    if len(cluster_points) > 1:
        cov = np.cov(cluster_points, rowvar=False)
        eigenvalues, eigenvectors = np.linalg.eigh(cov)
        angle = np.degrees(np.arctan2(eigenvectors[1, 0], eigenvectors[0, 0]))
        width, height = 2 * np.sqrt(eigenvalues) * 2  # Multiplicador de escala de elipse
        ellipse = Ellipse(xy=centroids_pca[i], width=width, height=height, angle=angle, color=color, alpha=0.15)
        plt.gca().add_patch(ellipse)

# Adicionar textos de nombres (colocamos muestra aleatoria de municipios para evitar saturación de texto)
for i, row in datos_pca_df.iterrows():
    if i % 15 == 0:  # Muestra texto cada 15 filas para que sea legible en los 884 registros
        plt.text(row['PCA1'], row['PCA2'] + 0.05, datos['State'][i], fontsize=7, ha='center', alpha=0.8)

plt.title('Algoritmo K-means con clusters k=4 y Elipses (Municipios Colombianos)', fontsize=18)
plt.xlabel('PCA1', fontsize=12)
plt.ylabel('PCA2', fontsize=12)
plt.text(datos_pca_df['PCA1'].max()-2, datos_pca_df['PCA2'].min(), "Inercia = %0.2f" % km4_clusters.inertia_, fontsize=14, bbox=dict(facecolor='white', alpha=0.5))
plt.legend()
plt.grid(True)
plt.show()

